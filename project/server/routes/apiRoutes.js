const router = require('express').Router();
const c = require('../controllers/resourceControllers');
const { protect, allow } = require('../middleware/auth');
const upload = require('../middleware/upload');

router.use(protect);
router.get('/users', allow('admin', 'manager'), c.users);
router.patch('/users/:id', allow('admin'), c.updateUser);
router.get('/teams', c.listTeams);
router.post('/teams', allow('admin', 'manager'), c.createTeam);
router.patch('/teams/:id', allow('admin', 'manager'), c.updateTeam);
router.patch('/teams/:id/members', allow('admin', 'manager'), c.setTeamMembers);
router.delete('/teams/:id', allow('admin'), c.deleteTeam);
router.get('/projects', c.listProjects);
router.post('/projects', allow('admin', 'manager'), c.createProject);
router.patch('/projects/:id', allow('admin', 'manager'), c.updateProject);
router.delete('/projects/:id', allow('admin'), c.deleteProject);
router.get('/tasks', c.listTasks);
router.get('/tasks/:id', c.getTask);
router.post('/tasks', allow('admin', 'manager'), c.createTask);
router.patch('/tasks/:id', c.updateTask);
router.delete('/tasks/:id', allow('admin', 'manager'), c.deleteTask);
router.post('/tasks/:id/attachments', upload.single('file'), c.addAttachment);
router.delete('/tasks/:id/attachments/:attachmentId', c.deleteAttachment);
router.get('/comments/task/:taskId', c.listComments);
router.post('/comments/task/:taskId', c.createComment);
router.patch('/comments/:id', c.updateComment);
router.delete('/comments/:id', c.deleteComment);
router.get('/notifications', c.notifications);
router.patch('/notifications/read-all', c.readAll);
router.patch('/notifications/:id/read', c.readNotification);
router.delete('/notifications/:id', c.deleteNotification);
router.get('/dashboard', c.dashboard);
router.get('/activity', allow('admin'), c.activity);
module.exports = router;
